import AppKit

/// Watches the general pasteboard. Copying the same text twice within
/// `NotesSettings.doubleCopyWindow` saves it as a note. Polling `changeCount` needs no permissions.
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    /// Called after a note is saved (shows the bubble).
    var onSaved: (() -> Void)?

    /// Password managers mark secrets with these types (nspasteboard.org); they are never saved.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ].map { NSPasteboard.PasteboardType($0) }

    private let pasteboard = NSPasteboard.general
    private var lastCount: Int
    private var lastCopy: (date: Date, text: String, app: String?)?
    /// changeCount of our own writes, ignored.
    private var ownCount: Int?
    private var timer: Timer?

    private init() { lastCount = NSPasteboard.general.changeCount }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.05, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardWatcher.shared.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Writes text to the clipboard without it counting as a copy.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        ownCount = pasteboard.changeCount
        lastCount = pasteboard.changeCount
        lastCopy = nil
    }

    /// Saves whatever text is on the clipboard now. Returns false if there is none.
    @discardableResult
    func saveCurrent() -> Bool {
        guard let text = readText() else { return false }
        return save(text, app: frontAppName())
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        if count == ownCount { return }
        // With the keyboard watcher running, it detects double copies (also when the clipboard doesn't change).
        guard NotesSettings.shared.doubleCopy, !KeyWatcher.shared.isRunning, let text = readText() else { lastCopy = nil; return }
        let now = Date()
        if let last = lastCopy, last.text == text,
           now.timeIntervalSince(last.date) <= NotesSettings.shared.doubleCopyWindow {
            save(text, app: last.app)
            // A third ⌘C starts again instead of saving once more.
            lastCopy = nil
        } else {
            lastCopy = (now, text, frontAppName())
        }
    }

    @discardableResult
    private func save(_ text: String, app: String?) -> Bool {
        guard NoteStore.shared.add(text, app: app) else { return false }
        onSaved?()
        return true
    }

    /// Plain text on the clipboard, unless it is marked as private.
    private func readText() -> String? {
        let types = pasteboard.types ?? []
        if types.contains(where: Self.privateTypes.contains) { return nil }
        return pasteboard.string(forType: .string)
    }

    private func frontAppName() -> String? {
        guard let app = NSWorkspace.shared.frontmostApplication,
              app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return nil }
        return app.localizedName
    }
}
